-- 13. FUNCTION: Get monthly calendar view
-- =====================================================
CREATE OR REPLACE FUNCTION get_monthly_calendar(
  p_user_id UUID,
  p_year INTEGER DEFAULT NULL,
  p_month INTEGER DEFAULT NULL
)
RETURNS JSON AS $$
DECLARE
  v_start DATE;
  v_end DATE;
  v_days JSON[];
  v_day DATE;
  v_day_data JSON;
BEGIN
  -- Default to current month
  IF p_year IS NULL THEN
    p_year := EXTRACT(YEAR FROM CURRENT_DATE)::INTEGER;
  END IF;
  IF p_month IS NULL THEN
    p_month := EXTRACT(MONTH FROM CURRENT_DATE)::INTEGER;
  END IF;
  
  v_start := make_date(p_year, p_month, 1);
  v_end := (v_start + INTERVAL '1 month - 1 day')::date;
  
  -- Build array for each day (simplified for month view)
  FOR v_day IN SELECT generate_series(v_start, v_end, '1 day'::interval)::date
  LOOP
    SELECT json_build_object(
      'date', v_day,
      'day', EXTRACT(DAY FROM v_day),
      'has_habits', (SELECT COUNT(*) > 0 FROM public.habit_logs hl 
        JOIN public.habits h ON h.id = hl.habit_id
        WHERE h.user_id = p_user_id AND hl.log_date = v_day),
      'has_events', (SELECT COUNT(*) > 0 FROM public.calendar_events e 
        WHERE e.user_id = p_user_id AND e.start_time::date = v_day),
      'completion_rate', (
        SELECT CASE WHEN habit_count > 0 
          THEN ROUND((completed_count::decimal / habit_count) * 100)
          ELSE 0 END
        FROM (
          SELECT 
            COUNT(*) FILTER (WHERE hl.id IS NOT NULL) as completed_count,
            COUNT(*) as habit_count
          FROM public.habits h
          LEFT JOIN public.habit_logs hl ON hl.habit_id = h.id AND hl.log_date = v_day
          WHERE h.user_id = p_user_id AND h.is_active = true
        ) sub
      )
    ) INTO v_day_data;
    
    v_days := array_append(v_days, v_day_data);
  END LOOP;
  
  RETURN json_build_object(
    'year', p_year,
    'month', p_month,
    'month_name', to_char(v_start, 'Month'),
    'days_in_month', EXTRACT(DAY FROM v_end),
    'first_day_weekday', EXTRACT(DOW FROM v_start),
    'days', v_days
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

