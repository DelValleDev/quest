-- 17. FUNCTION: Complete agenda item
-- =====================================================
CREATE OR REPLACE FUNCTION complete_agenda_item(
  p_user_id UUID,
  p_item_id UUID
)
RETURNS JSON AS $$
DECLARE
  v_item public.daily_agenda_items%ROWTYPE;
  v_result JSON;
BEGIN
  SELECT * INTO v_item
  FROM public.daily_agenda_items
  WHERE id = p_item_id AND user_id = p_user_id;
  
  IF v_item IS NULL THEN
    RETURN json_build_object('success', false, 'error', 'Item not found');
  END IF;
  
  -- Handle based on type
  IF v_item.item_type = 'habit' AND v_item.habit_id IS NOT NULL THEN
    v_result := complete_habit(v_item.habit_id, p_user_id, NULL, NULL);
    
  ELSIF v_item.item_type = 'quest' AND v_item.quest_id IS NOT NULL THEN
    v_result := respond_to_ai_quest(p_user_id, v_item.quest_id, 'complete');
    
  ELSIF v_item.item_type = 'event' AND v_item.event_id IS NOT NULL THEN
    UPDATE public.calendar_events
    SET status = 'completed'
    WHERE id = v_item.event_id;
    v_result := json_build_object('success', true, 'type', 'event');
  END IF;
  
  -- Update agenda item
  UPDATE public.daily_agenda_items
  SET status = 'completed', completed_at = NOW(), updated_at = NOW()
  WHERE id = p_item_id;
  
  RETURN json_build_object(
    'success', true,
    'item_type', v_item.item_type,
    'result', v_result
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

