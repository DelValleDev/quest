-- =====================================================
-- 1. INTERNAL CALENDAR EVENTS (No external dependency)
-- =====================================================
CREATE TABLE IF NOT EXISTS public.calendar_events (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
  
  -- Basic info
  title TEXT NOT NULL,
  description TEXT,
  
  -- Time
  start_time TIMESTAMPTZ NOT NULL,
  end_time TIMESTAMPTZ NOT NULL,
  is_all_day BOOLEAN DEFAULT false,
  
  -- Recurrence
  is_recurring BOOLEAN DEFAULT false,
  recurrence_rule TEXT, -- 'daily', 'weekly', 'monthly', 'weekdays'
  recurrence_end_date DATE,
  parent_event_id UUID REFERENCES public.calendar_events(id) ON DELETE CASCADE,
  
  -- Categorization
  event_type TEXT DEFAULT 'personal' CHECK (event_type IN ('personal', 'work', 'social', 'health', 'other')),
  color TEXT DEFAULT '#6366F1',
  icon TEXT DEFAULT '📅',
  
  -- Location (optional)
  location TEXT,
  
  -- Reminders
  reminder_minutes INTEGER[] DEFAULT ARRAY[10, 30],
  
  -- Source
  source TEXT DEFAULT 'manual' CHECK (source IN ('manual', 'ai_generated', 'synced_google', 'synced_apple')),
  external_id TEXT, -- For synced events
  
  -- Status
  status TEXT DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'completed', 'cancelled')),
  
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- =====================================================
-- 2. DAILY AGENDA ITEMS - Unified view of the day
-- =====================================================
CREATE TABLE IF NOT EXISTS public.daily_agenda_items (
  id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
  
  -- Date and time
  agenda_date DATE NOT NULL DEFAULT CURRENT_DATE,
  start_time TIME,
  end_time TIME,
  is_all_day BOOLEAN DEFAULT false,
  
  -- Item type
  item_type TEXT NOT NULL CHECK (item_type IN ('habit', 'quest', 'event', 'blocked')),
  
  -- References
  habit_id UUID REFERENCES public.habits(id) ON DELETE CASCADE,
  quest_id UUID,
  event_id UUID REFERENCES public.calendar_events(id) ON DELETE CASCADE,
  
  -- Display info
  title TEXT NOT NULL,
  description TEXT,
  icon TEXT DEFAULT '📌',
  color TEXT DEFAULT '#6B7280',
  pillar_id TEXT,
  
  -- Status
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'in_progress', 'completed', 'skipped', 'rescheduled')),
  completed_at TIMESTAMPTZ,
  
  -- Priority (1 = highest)
  priority INTEGER DEFAULT 5,
  duration_minutes INTEGER DEFAULT 15,
  
  -- Source
  created_by TEXT DEFAULT 'manual' CHECK (created_by IN ('manual', 'ai_generated', 'system')),
  
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- =====================================================
-- 3. AI DAILY QUESTS - Generated by AI each day
-- =====================================================
