-- 10. FUNCTION: Get calendar events for date range
-- =====================================================
CREATE OR REPLACE FUNCTION get_calendar_events(
  p_user_id UUID,
  p_start_date DATE,
  p_end_date DATE
)
RETURNS TABLE (
  id UUID,
  title TEXT,
  description TEXT,
  start_time TIMESTAMPTZ,
  end_time TIMESTAMPTZ,
  is_all_day BOOLEAN,
  event_type TEXT,
  color TEXT,
  icon TEXT,
  status TEXT,
  source TEXT
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    e.id, e.title, e.description,
    e.start_time, e.end_time, e.is_all_day,
    e.event_type, e.color, e.icon, e.status, e.source
  FROM public.calendar_events e
  WHERE e.user_id = p_user_id
    AND e.start_time::date >= p_start_date
    AND e.start_time::date <= p_end_date
    AND e.status != 'cancelled'
  ORDER BY e.start_time;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

