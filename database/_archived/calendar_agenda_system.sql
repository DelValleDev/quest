-- 11. FUNCTION: Generate daily agenda
-- =====================================================
CREATE OR REPLACE FUNCTION generate_daily_agenda(
  p_user_id UUID,
  p_date DATE DEFAULT CURRENT_DATE
)
RETURNS TABLE (
  id UUID,
  start_time TIME,
  end_time TIME,
  item_type TEXT,
  title TEXT,
  description TEXT,
  icon TEXT,
  color TEXT,
  pillar_id TEXT,
  status TEXT,
  duration_minutes INTEGER,
  priority INTEGER,
  reference_id UUID
) AS $$
BEGIN
  -- Clear and regenerate agenda for this day
  DELETE FROM public.daily_agenda_items
  WHERE user_id = p_user_id AND agenda_date = p_date;
  
  -- Insert habits
  INSERT INTO public.daily_agenda_items (
    user_id, agenda_date, start_time, item_type, habit_id,
    title, description, icon, color, pillar_id, status, priority, duration_minutes, created_by
  )
  SELECT 
    p_user_id, p_date, h.preferred_time, 'habit', h.id,
    h.title, h.description, h.icon,
    COALESCE(p.color, '#10B981'), h.pillar_id,
    CASE WHEN hl.id IS NOT NULL THEN 'completed' ELSE 'pending' END,
    CASE h.time_of_day
      WHEN 'morning' THEN 1
      WHEN 'afternoon' THEN 2
      WHEN 'evening' THEN 3
      ELSE 4
    END,
    15, 'system'
  FROM public.habits h
  LEFT JOIN public.pillars p ON p.id = h.pillar_id
  LEFT JOIN public.habit_logs hl ON hl.habit_id = h.id AND hl.log_date = p_date
  WHERE h.user_id = p_user_id AND h.is_active = true
    AND (h.frequency = 'daily' 
      OR (h.frequency = 'specific_days' AND LOWER(trim(to_char(p_date, 'day'))) = ANY(h.frequency_days)));
  
  -- Insert calendar events
  INSERT INTO public.daily_agenda_items (
    user_id, agenda_date, start_time, end_time, item_type, event_id,
    title, description, icon, color, status, priority, duration_minutes, created_by
  )
  SELECT 
    p_user_id, p_date, e.start_time::time, e.end_time::time, 'event', e.id,
    e.title, e.description, e.icon, e.color, 'pending', 2,
    EXTRACT(EPOCH FROM (e.end_time - e.start_time)) / 60,
    CASE e.source WHEN 'ai_generated' THEN 'ai_generated' ELSE 'manual' END
  FROM public.calendar_events e
  WHERE e.user_id = p_user_id
    AND e.start_time::date = p_date
    AND e.status = 'scheduled';
  
  -- Insert AI daily quests that were accepted
  INSERT INTO public.daily_agenda_items (
    user_id, agenda_date, item_type, quest_id,
    title, description, icon, color, pillar_id, status, priority, duration_minutes, created_by
  )
  SELECT 
    p_user_id, p_date, 'quest', q.id,
    q.title, q.description, q.icon,
    COALESCE(pl.color, '#F59E0B'), q.pillar_id,
    CASE WHEN q.status = 'completed' THEN 'completed' ELSE 'pending' END,
    3, q.estimated_minutes, 'ai_generated'
  FROM public.ai_daily_quests q
  LEFT JOIN public.pillars pl ON pl.id = q.pillar_id
  WHERE q.user_id = p_user_id
    AND q.quest_date = p_date
    AND q.status IN ('accepted', 'completed');
  
  -- Return the agenda
  RETURN QUERY
  SELECT 
    dai.id, dai.start_time, dai.end_time, dai.item_type,
    dai.title, dai.description, dai.icon, dai.color,
    dai.pillar_id, dai.status, dai.duration_minutes, dai.priority,
    COALESCE(dai.habit_id, dai.quest_id, dai.event_id)
  FROM public.daily_agenda_items dai
  WHERE dai.user_id = p_user_id AND dai.agenda_date = p_date
  ORDER BY dai.priority, dai.start_time NULLS LAST;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

