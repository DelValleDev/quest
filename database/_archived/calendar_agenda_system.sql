-- =====================================================
-- 5. FUNCTION: Check if user has premium access
-- =====================================================
CREATE OR REPLACE FUNCTION has_premium_access(p_user_id UUID)
RETURNS BOOLEAN AS $$
DECLARE
  v_profile public.profiles%ROWTYPE;
BEGIN
  SELECT * INTO v_profile FROM public.profiles WHERE id = p_user_id;
  
  IF v_profile IS NULL THEN
    RETURN false;
  END IF;
  
  -- Developers always have premium
  IF v_profile.is_developer = true THEN
    RETURN true;
  END IF;
  
  -- Check premium status
  IF v_profile.is_premium = true AND 
     (v_profile.premium_expires_at IS NULL OR v_profile.premium_expires_at > NOW()) THEN
    RETURN true;
  END IF;
  
  RETURN false;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- =====================================================
-- 6. FUNCTION: Set developer status (run once for yourself)
-- =====================================================
CREATE OR REPLACE FUNCTION set_developer_status(p_email TEXT)
RETURNS JSON AS $$
DECLARE
  v_user_id UUID;
BEGIN
  -- Find user by email in auth.users
  SELECT id INTO v_user_id
  FROM auth.users
  WHERE email = p_email;
  
  IF v_user_id IS NULL THEN
    RETURN json_build_object('success', false, 'error', 'User not found');
  END IF;
  
  -- Update profile
  UPDATE public.profiles
  SET is_developer = true, is_premium = true
  WHERE id = v_user_id;
  
  RETURN json_build_object(
    'success', true,
    'user_id', v_user_id,
    'message', 'Developer status granted - permanent premium access'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- =====================================================
-- 7. FUNCTION: Check and use AI calendar action
-- =====================================================
CREATE OR REPLACE FUNCTION use_ai_calendar_action(p_user_id UUID)
RETURNS JSON AS $$
DECLARE
  v_profile public.profiles%ROWTYPE;
  v_is_premium BOOLEAN;
BEGIN
  SELECT * INTO v_profile FROM public.profiles WHERE id = p_user_id;
  v_is_premium := has_premium_access(p_user_id);
  
  -- Reset counter if new day
  IF v_profile.ai_calendar_last_reset IS NULL OR 
     v_profile.ai_calendar_last_reset < CURRENT_DATE THEN
    UPDATE public.profiles
    SET ai_calendar_uses_today = 0, ai_calendar_last_reset = CURRENT_DATE
    WHERE id = p_user_id;
    
    v_profile.ai_calendar_uses_today := 0;
  END IF;
  
  -- Premium users have unlimited
  IF v_is_premium THEN
    UPDATE public.profiles
    SET ai_calendar_uses_today = ai_calendar_uses_today + 1
    WHERE id = p_user_id;
    
    RETURN json_build_object(
      'allowed', true,
      'is_premium', true,
      'uses_today', v_profile.ai_calendar_uses_today + 1,
      'limit', 'unlimited'
    );
  END IF;
  
  -- Free users: 1 per day
  IF v_profile.ai_calendar_uses_today >= 1 THEN
    RETURN json_build_object(
      'allowed', false,
      'is_premium', false,
      'uses_today', v_profile.ai_calendar_uses_today,
      'limit', 1,
      'message', 'Ya usaste tu ayuda de IA del día. Actualiza a Premium para acceso ilimitado.'
    );
  END IF;
  
  UPDATE public.profiles
  SET ai_calendar_uses_today = ai_calendar_uses_today + 1
  WHERE id = p_user_id;
  
  RETURN json_build_object(
    'allowed', true,
    'is_premium', false,
    'uses_today', v_profile.ai_calendar_uses_today + 1,
    'limit', 1
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

