-- 15. FUNCTION: Accept or skip AI quest
-- =====================================================
CREATE OR REPLACE FUNCTION respond_to_ai_quest(
  p_user_id UUID,
  p_quest_id UUID,
  p_action TEXT -- 'accept', 'skip', 'complete'
)
RETURNS JSON AS $$
DECLARE
  v_quest public.ai_daily_quests%ROWTYPE;
BEGIN
  SELECT * INTO v_quest 
  FROM public.ai_daily_quests 
  WHERE id = p_quest_id AND user_id = p_user_id;
  
  IF v_quest IS NULL THEN
    RETURN json_build_object('success', false, 'error', 'Quest not found');
  END IF;
  
  IF p_action = 'accept' THEN
    UPDATE public.ai_daily_quests
    SET status = 'accepted'
    WHERE id = p_quest_id;
    
  ELSIF p_action = 'skip' THEN
    UPDATE public.ai_daily_quests
    SET status = 'skipped'
    WHERE id = p_quest_id;
    
  ELSIF p_action = 'complete' THEN
    UPDATE public.ai_daily_quests
    SET status = 'completed', completed_at = NOW()
    WHERE id = p_quest_id;
    
    -- Award XP and coins
    UPDATE public.profiles
    SET 
      total_xp = total_xp + v_quest.xp_reward,
      quest_coins = quest_coins + v_quest.coin_reward
    WHERE id = p_user_id;
    
    RETURN json_build_object(
      'success', true,
      'action', 'completed',
      'xp_earned', v_quest.xp_reward,
      'coins_earned', v_quest.coin_reward
    );
  END IF;
  
  RETURN json_build_object('success', true, 'action', p_action);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

