-- 16. FUNCTION: Get today's AI quests
-- =====================================================
CREATE OR REPLACE FUNCTION get_ai_daily_quests(
  p_user_id UUID,
  p_date DATE DEFAULT CURRENT_DATE
)
RETURNS TABLE (
  id UUID,
  title TEXT,
  description TEXT,
  icon TEXT,
  pillar_id TEXT,
  difficulty TEXT,
  xp_reward INTEGER,
  coin_reward INTEGER,
  estimated_minutes INTEGER,
  suggested_time TEXT,
  status TEXT
) AS $$
BEGIN
  RETURN QUERY
  SELECT 
    q.id, q.title, q.description, q.icon, q.pillar_id,
    q.difficulty, q.xp_reward, q.coin_reward,
    q.estimated_minutes, q.suggested_time, q.status
  FROM public.ai_daily_quests q
  WHERE q.user_id = p_user_id
    AND q.quest_date = p_date
    AND q.status != 'expired'
  ORDER BY 
    CASE q.status
      WHEN 'available' THEN 1
      WHEN 'accepted' THEN 2
      WHEN 'completed' THEN 3
      ELSE 4
    END,
    q.created_at;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

