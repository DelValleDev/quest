-- 18. FUNCTION: Get agenda summary
-- =====================================================
CREATE OR REPLACE FUNCTION get_agenda_summary(
  p_user_id UUID,
  p_date DATE DEFAULT CURRENT_DATE
)
RETURNS JSON AS $$
DECLARE
  v_total INTEGER;
  v_completed INTEGER;
  v_habits_total INTEGER;
  v_habits_completed INTEGER;
  v_quests_total INTEGER;
  v_quests_completed INTEGER;
  v_events_total INTEGER;
BEGIN
  SELECT 
    COUNT(*),
    COUNT(*) FILTER (WHERE status = 'completed')
  INTO v_total, v_completed
  FROM public.daily_agenda_items
  WHERE user_id = p_user_id AND agenda_date = p_date;
  
  SELECT 
    COUNT(*),
    COUNT(*) FILTER (WHERE status = 'completed')
  INTO v_habits_total, v_habits_completed
  FROM public.daily_agenda_items
  WHERE user_id = p_user_id AND agenda_date = p_date AND item_type = 'habit';
  
  SELECT 
    COUNT(*),
    COUNT(*) FILTER (WHERE status = 'completed')
  INTO v_quests_total, v_quests_completed
  FROM public.daily_agenda_items
  WHERE user_id = p_user_id AND agenda_date = p_date AND item_type = 'quest';
  
  SELECT COUNT(*) INTO v_events_total
  FROM public.daily_agenda_items
  WHERE user_id = p_user_id AND agenda_date = p_date AND item_type = 'event';
  
  RETURN json_build_object(
    'date', p_date,
    'total_items', v_total,
    'completed', v_completed,
    'progress_percentage', CASE WHEN v_total > 0 THEN ROUND((v_completed::decimal / v_total) * 100) ELSE 0 END,
    'habits', json_build_object('total', v_habits_total, 'completed', v_habits_completed),
    'quests', json_build_object('total', v_quests_total, 'completed', v_quests_completed),
    'events', json_build_object('total', v_events_total)
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

