-- 12. FUNCTION: Get weekly calendar view
-- =====================================================
CREATE OR REPLACE FUNCTION get_weekly_calendar(
  p_user_id UUID,
  p_week_start DATE DEFAULT NULL
)
RETURNS JSON AS $$
DECLARE
  v_start DATE;
  v_end DATE;
  v_days JSON[];
  v_day DATE;
  v_day_data JSON;
BEGIN
  -- Default to current week (Monday start)
  IF p_week_start IS NULL THEN
    v_start := date_trunc('week', CURRENT_DATE)::date;
  ELSE
    v_start := p_week_start;
  END IF;
  v_end := v_start + INTERVAL '6 days';
  
  -- Build array for each day
  FOR v_day IN SELECT generate_series(v_start, v_end, '1 day'::interval)::date
  LOOP
    SELECT json_build_object(
      'date', v_day,
      'day_name', to_char(v_day, 'Dy'),
      'habits_count', (SELECT COUNT(*) FROM public.habits h 
        WHERE h.user_id = p_user_id AND h.is_active = true),
      'habits_completed', (SELECT COUNT(*) FROM public.habit_logs hl 
        JOIN public.habits h ON h.id = hl.habit_id
        WHERE h.user_id = p_user_id AND hl.log_date = v_day),
      'events_count', (SELECT COUNT(*) FROM public.calendar_events e 
        WHERE e.user_id = p_user_id AND e.start_time::date = v_day AND e.status = 'scheduled'),
      'quests_count', (SELECT COUNT(*) FROM public.ai_daily_quests q 
        WHERE q.user_id = p_user_id AND q.quest_date = v_day AND q.status IN ('accepted', 'available'))
    ) INTO v_day_data;
    
    v_days := array_append(v_days, v_day_data);
  END LOOP;
  
  RETURN json_build_object(
    'week_start', v_start,
    'week_end', v_end,
    'days', v_days
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

